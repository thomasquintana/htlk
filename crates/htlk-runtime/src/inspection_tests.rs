#[test]
fn authored_edges_recorded_selection_loops_and_extension_origins_stay_distinct() {
    actix::System::new().block_on(async {
        let store = Store::in_memory(StoreConfig::default()).await.unwrap();
        let admitted = graph(&store,"origin.old").await;
        let run = run(&store,&admitted,"navigation-run").await;
        let l = Limits::default();
        let root_definition = admitted.document().fields().root_scope;
        let root = &admitted.document().fields().scopes[&root_definition];
        let body = root.fields().nodes.iter().find_map(|n|match n.fields().operation { Operation::Loop { body,.. } =>Some(body),_=>None }).unwrap();
        let repeat = InvocationId::new(run.root,&"repeat".parse().unwrap(),&l).unwrap();
        let repeat_node = root.fields().nodes.iter().find(|n|n.id().as_str()=="repeat").unwrap();
        let repeat_payload = object([
            ("scope_instance_id",text(run.root)),("local_id",text("repeat")),("definition_digest",text(repeat_node.digest(&l).unwrap())),
            ("origin_executable",text(admitted.fingerprint())),("status",text("active")),
        ]);
        let mut writes = vec![write(RecordFamily::Invocation,repeat,None,repeat_payload),
            write(RecordFamily::Binding,format!("{}:work:x",run.root),None,object([
                ("state",text("absent")),("selected_edge",text("right")),("influence_labels",labels().to_value(&l).unwrap()),
            ])),
            write(RecordFamily::Attempt,"attempt-one",None,object([("invocation_id",text(run.work)),("state",text("prepared"))])),
            write(RecordFamily::Wait,"wait-one",None,object([("invocation_id",text(run.work)),("state",text("open"))])),
        ];
        let mut iterations = Vec::new();
        for index in 0..2 {
            let instance = ScopeInstanceId::iteration(repeat,index,&l).unwrap();
            iterations.push(instance);
            writes.push(write(RecordFamily::Scope,instance,None,object([
                ("definition_digest",text(body)),("origin_executable",text(admitted.fingerprint())),("parent_invocation",text(repeat)),
                ("iteration",Value::Integer(index as i64)),("scope_use",Value::Array(vec![text("node"),text(root_definition),text("repeat")])),
                ("status",text("succeeded")),
            ])));
        }
        store.commit(&run.lease,transition("recorded",writes)).await.unwrap();
        let policy = Policy::all();
        let inspector = Inspector::new(store.clone(),policy.clone());
        let host = context("host",None);
        let old = inspector.open_snapshot(&host,RunSelector::Id(run.id.clone()),None).await.unwrap();
        let graph_ref = inspector.select(&host,&old,EntityId::Graph(admitted.fingerprint())).await.unwrap().reference;
        let definition = inspector.select(&host,&old,EntityId::ScopeDefinition { executable:admitted.fingerprint(),scope:root_definition }).await.unwrap().reference;
        let authored = inspector.follow_relations(&host,&old,&definition,RelationKind::AuthoredChild,PageRequest::new(256)).await.unwrap();
        assert_eq!(authored.items.len(),5); // three nodes and two potential edges
        assert!(!format!("{authored:?}").contains("literal secret"));
        assert!(inspector.follow_relations(&host,&old,&graph_ref,RelationKind::ExecutionChild,PageRequest::new(256)).await.unwrap().items.is_empty());
        let work = reference(&old,RecordFamily::Invocation,run.work);
        assert!(inspector.follow_relations(&host,&old,&work,RelationKind::AuthoredDataflow(DataflowEnd::Source),PageRequest::new(256)).await.unwrap().items.is_empty());
        let bindings = inspector.follow_relations(&host,&old,&work,RelationKind::Bindings,PageRequest::new(256)).await.unwrap();
        assert_eq!(bindings.items.len(),1);
        let binding = &bindings.items[0].target;
        let chosen = inspector.follow_relations(&host,&old,binding,RelationKind::SelectedEdge,PageRequest::new(256)).await.unwrap();
        assert_eq!(chosen.items.len(),1);
        assert!(matches!(chosen.items[0].target.entity(),EntityId::EdgeDefinition { edge,.. } if edge.as_str()=="right"));
        *policy.hidden.lock().unwrap() = Some(chosen.items[0].target.entity.clone());
        assert!(inspector.follow_relations(&host,&old,binding,RelationKind::SelectedEdge,PageRequest::new(256)).await.unwrap().items.is_empty());
        *policy.hidden.lock().unwrap() = None;
        assert!(inspector.follow_relations(&host,&old,binding,RelationKind::SelectedArtifact,PageRequest::new(256)).await.unwrap().items.is_empty());
        assert_eq!(inspector.follow_relations(&host,&old,&work,RelationKind::Attempts,PageRequest::new(256)).await.unwrap().items.len(),1);
        assert_eq!(inspector.follow_relations(&host,&old,&work,RelationKind::Waits,PageRequest::new(256)).await.unwrap().items.len(),1);
        let chosen_source = inspector.follow_relations(&host,&old,&chosen.items[0].target,RelationKind::AuthoredDataflow(DataflowEnd::Source),PageRequest::new(256)).await.unwrap();
        assert_eq!(chosen_source.items[0].target.entity(),definition.entity());
        let children = inspector.follow_relations(&host,&old,&reference(&old,RecordFamily::Invocation,repeat),RelationKind::ExecutionChild,PageRequest::new(256)).await.unwrap();
        assert_eq!(children.items.len(),2);
        let mut identities = Vec::new();
        for (index,instance) in iterations.iter().enumerate() {
            let inspected = inspector.inspect_entity(&host,&old,&reference(&old,RecordFamily::Scope,instance)).await.unwrap();
            assert_eq!(inspected.iteration,Some(index as u64));
            assert!(matches!(inspected.scope_use,Some(htlk_analyzer::ScopeUse::Node {..})));
            identities.push(inspected.definition.unwrap());
        }
        assert_eq!(identities[0],identities[1]);
        let composed = graph(&store,"origin.composed").await;
        let new_root = ScopeInstanceId::extended_root(&run.id,1,&l).unwrap();
        let mut extension = transition("extend",vec![
            write(RecordFamily::Scope,new_root,None,object([
                ("definition_digest",text(composed.document().fields().root_scope)),("origin_executable",text(composed.fingerprint())),
                ("extension_number",Value::Integer(1)),("scope_use",Value::Array(vec![text("root")])),("status",text("active")),
            ])),
            write(RecordFamily::Extension,"1",None,object([
                ("preserved_scope",text(run.root)),("preserved_wrapper",text(run.work)),("new_root",text(new_root)),
                ("previous_fingerprint",text(admitted.fingerprint())),("active_fingerprint",text(composed.fingerprint())),
            ])),
        ]);
        extension.root = Some(RootReplacement { fingerprint:composed.fingerprint(),root_scope:new_root });
        store.commit(&run.lease,extension).await.unwrap();
        let latest = inspector.refresh_snapshot(&host,&old).await.unwrap();
        let old_instance = reference(&latest,RecordFamily::Invocation,run.work);
        let original = inspector.follow_relations(&host,&latest,&old_instance,RelationKind::InstanceOf,PageRequest::new(256)).await.unwrap();
        assert_eq!(original.items.len(),1);
        assert!(matches!(original.items[0].target.entity(),EntityId::NodeDefinition { executable,.. } if *executable==admitted.fingerprint()));
        let transported = Reference::decode(&original.items[0].target.encode(&l).unwrap(),&l).unwrap();
        assert_eq!(inspector.resolve_reference(&host,&transported).await.unwrap().1.definition.unwrap().executable,admitted.fingerprint());
        let reuses = inspector.follow_relations(&host,&latest,&reference(&latest,RecordFamily::Extension,"1"),RelationKind::Reuses,PageRequest::new(256)).await.unwrap();
        assert_eq!(reuses.items.len(),3);
        let old_graph = reuses.items.iter().find(|r|matches!(r.target.entity(),EntityId::Graph(_))).unwrap();
        assert_eq!(inspector.resolve_reference(&host,&old_graph.target).await.unwrap().1.definition.unwrap().executable,admitted.fingerprint());
        assert_eq!(inspector.inspect_entity(&host,&old,&graph_ref).await.unwrap().definition.unwrap().executable,admitted.fingerprint());
    });
}

