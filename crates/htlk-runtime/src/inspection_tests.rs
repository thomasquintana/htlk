struct Policy {
    discover: AtomicBool,
    structure: AtomicBool,
    content: AtomicBool,
    hidden: Mutex<Option<EntityId>>,
}
impl Policy {
    fn all() -> Arc<Self> {
        Arc::new(Self {
            discover: AtomicBool::new(true),
            structure: AtomicBool::new(true),
            content: AtomicBool::new(true),
            hidden: Mutex::new(None),
        })
    }
}
impl InspectionPolicy for Policy {
    fn discover(&self, context: &InspectionContext, target: &DiscoveryTarget<'_>) -> bool {
        self.discover.load(Ordering::SeqCst)
            && (context.host().principal() != "self"
                || context.caller_run() == Some(target.reference.run_id()))
            && self.hidden.lock().unwrap().as_ref() != Some(target.reference.entity())
    }
    fn structure(&self, _: &InspectionContext, _: &InspectionTarget<'_>) -> bool {
        self.structure.load(Ordering::SeqCst)
    }
    fn content(&self, _: &InspectionContext, _: &InspectionTarget<'_>, _: ContentKind) -> bool {
        self.content.load(Ordering::SeqCst)
    }
}
fn context(principal: &str, caller_run: Option<RunId>) -> InspectionContext {
    InspectionContext::new(
        HostContext::new(principal.into(), &Limits::default()).unwrap(),
        caller_run,
    )
}
fn object(entries: impl IntoIterator<Item = (&'static str, Value)>) -> Value {
    Value::Map(Map::try_from_entries(entries.into_iter().map(|(k, v)| (k.into(), v))).unwrap())
}
fn text(s: impl ToString) -> Value {
    Value::Text(s.to_string())
}
fn labels() -> SecurityLabels {
    SecurityLabels::new(vec!["source-secret".into()], &Limits::default()).unwrap()
}
fn ports(name: &str) -> PortTable {
    PortTable::new(
        vec![(
            name.parse().unwrap(),
            Port::new(ValueType::builtin(BuiltinType::String), true),
        )],
        &Limits::default(),
    )
    .unwrap()
}
fn literal(value: ScalarLiteral) -> Expression {
    Expression::new(ExpressionKind::Literal(value), &Limits::default()).unwrap()
}

async fn graph(store: &Store, name: &str) -> VerifiedExecutable<'static> {
    let l = Limits::default();
    // Reuse an intentional fixture as authored input, relinking only in memory;
    // no golden or manifest is regenerated by the test.
    let fixture = include_str!("../tests/fixtures/native-empty.hex")
        .lines()
        .skip(2)
        .collect::<String>();
    let bytes = fixture
        .as_bytes()
        .as_chunks::<2>()
        .0
        .iter()
        .map(|pair| u8::from_str_radix(std::str::from_utf8(pair).unwrap(), 16).unwrap())
        .collect::<Vec<_>>();
    let doc =
        CanonicalDocument::from_envelope(&ExecutableEnvelope::decode(&bytes, &l).unwrap(), &l)
            .unwrap();
    let mut fields = doc.fields().clone();
    let policy = PolicyDocument::from_document(
        fields.documents[&fields.profile.policy_document()].clone(),
        &l,
    )
    .unwrap();
    let mut registry = NativeRegistry::new(&l).unwrap();
    fields.profile = registry.link_policy(&policy).unwrap();
    fields.graph_id = name.into();
    let body = Scope::new(ScopeFields::default(), &l).unwrap();
    let body_id = body.digest(&l).unwrap();
    let mut work = NodeFields::new(
        "work".parse().unwrap(),
        Operation::Eval(literal(ScalarLiteral::String("literal secret".into()))),
    );
    work.inputs = ports("x");
    work.outputs = ports("value");
    let work = Node::new(work, &l).unwrap();
    let repeat = Node::new(
        NodeFields::new(
            "repeat".parse().unwrap(),
            Operation::Loop {
                body: body_id,
                initializers: vec![],
                until: literal(ScalarLiteral::Boolean(true)),
                max_iterations: 2,
            },
        ),
        &l,
    )
    .unwrap();
    let mount = Node::new(
        NodeFields::new("mount".parse().unwrap(), Operation::Scope(body_id)),
        &l,
    )
    .unwrap();
    let observed = ["mount", "repeat", "work"].into_iter().fold(
        literal(ScalarLiteral::Boolean(true)),
        |left, name| {
            let right = Expression::new(
                ExpressionKind::Binary {
                    operator: htlk_executable::BinaryOperator::Eq,
                    left: Box::new(
                        Expression::new(ExpressionKind::Status(name.parse().unwrap()), &l).unwrap(),
                    ),
                    right: Box::new(literal(ScalarLiteral::String("succeeded".into()))),
                },
                &l,
            )
            .unwrap();
            Expression::new(
                ExpressionKind::Binary {
                    operator: htlk_executable::BinaryOperator::And,
                    left: Box::new(left),
                    right: Box::new(right),
                },
                &l,
            )
            .unwrap()
        },
    );
    let root = Scope::new(
        ScopeFields {
            postconditions: observed,
            inputs: PortTable::new(
                vec![
                    (
                        "first".parse().unwrap(),
                        Port::new(ValueType::builtin(BuiltinType::String), true),
                    ),
                    (
                        "second".parse().unwrap(),
                        Port::new(ValueType::builtin(BuiltinType::String), true),
                    ),
                ],
                &l,
            )
            .unwrap(),
            nodes: vec![work, mount, repeat],
            edges: vec![
                Edge::new(
                    "left".parse().unwrap(),
                    EdgeSource::Input("first".parse().unwrap()),
                    EdgeDestination::Input {
                        node: "work".parse().unwrap(),
                        port: "x".parse().unwrap(),
                    },
                )
                .with_guard(literal(ScalarLiteral::Boolean(false))),
                Edge::new(
                    "right".parse().unwrap(),
                    EdgeSource::Input("second".parse().unwrap()),
                    EdgeDestination::Input {
                        node: "work".parse().unwrap(),
                        port: "x".parse().unwrap(),
                    },
                ),
            ],
            ..ScopeFields::default()
        },
        &l,
    )
    .unwrap();
    fields.root_scope = root.digest(&l).unwrap();
    fields.scopes.clear();
    fields.scopes.insert(body_id, body);
    fields.scopes.insert(fields.root_scope, root);
    let bytes = CanonicalDocument::new(fields, &l)
        .unwrap()
        .envelope(&l)
        .unwrap()
        .encode(&l)
        .unwrap();
    let admitted = verify_executable_owned(&bytes, Arc::new(registry), &l).unwrap();
    store
        .store_graph(&admitted, &bytes, &Value::Null)
        .await
        .unwrap();
    admitted
}
fn write(
    family: RecordFamily,
    id: impl ToString,
    revision: Option<i64>,
    payload: Value,
) -> RecordWrite {
    RecordWrite {
        key: RecordKey {
            family,
            id: id.to_string(),
        },
        expected_revision: revision,
        final_record: false,
        payload,
    }
}
fn transition(command: &str, writes: Vec<RecordWrite>) -> Transition {
    Transition {
        context: TransitionContext {
            command_id: command.into(),
            actor: "host-secret".into(),
            causation: "cause-secret".into(),
            timestamp_ms: 1,
        },
        writes,
        next_status: None,
        root: None,
        expected_fingerprint: None,
    }
}
struct Run {
    id: RunId,
    root: ScopeInstanceId,
    work: InvocationId,
    lease: RunLease,
}
async fn run(store: &Store, admitted: &VerifiedExecutable<'_>, name: &str) -> Run {
    let l = Limits::default();
    let id = RunId::new(name.into(), &l).unwrap();
    let root = ScopeInstanceId::root(&id, &l).unwrap();
    store
        .create_run(RunSeed {
            run_id: id.clone(),
            fingerprint: admitted.fingerprint(),
            root_scope: root,
            actor: "host-secret".into(),
            causation: "start-secret".into(),
            timestamp_ms: 0,
        })
        .await
        .unwrap();
    let lease = store
        .acquire(&id, "owner-secret".into(), 0, 1000)
        .await
        .unwrap();
    let work = InvocationId::new(root, &"work".parse().unwrap(), &l).unwrap();
    let node = admitted.document().fields().scopes[&admitted.document().fields().root_scope]
        .fields()
        .nodes
        .iter()
        .find(|n| n.id().as_str() == "work")
        .unwrap();
    store
        .commit(
            &lease,
            transition(
                "init",
                vec![
                    write(
                        RecordFamily::Scope,
                        root,
                        None,
                        object([
                            (
                                "definition_digest",
                                text(admitted.document().fields().root_scope),
                            ),
                            ("origin_executable", text(admitted.fingerprint())),
                            ("scope_use", Value::Array(vec![text("root")])),
                            ("status", text("active")),
                            ("influence_labels", labels().to_value(&l).unwrap()),
                            ("private", text("root-secret")),
                        ]),
                    ),
                    write(
                        RecordFamily::Invocation,
                        work,
                        None,
                        object([
                            ("scope_instance_id", text(root)),
                            ("local_id", text("work")),
                            ("definition_digest", text(node.digest(&l).unwrap())),
                            ("origin_executable", text(admitted.fingerprint())),
                            ("status", text("pending")),
                            ("influence_labels", labels().to_value(&l).unwrap()),
                            ("private", text("invocation-secret")),
                        ]),
                    ),
                    write(
                        RecordFamily::Observation,
                        "mcp-recorded",
                        None,
                        object([
                            ("invocation_id", text(work)),
                            ("influence_labels", labels().to_value(&l).unwrap()),
                            (
                                "response",
                                object([
                                    ("security_labels", Value::Integer(99)),
                                    ("value", text("response-secret")),
                                ]),
                            ),
                        ]),
                    ),
                ],
            ),
        )
        .await
        .unwrap();
    Run {
        id,
        root,
        work,
        lease,
    }
}
fn reference(snapshot: &Snapshot, family: RecordFamily, id: impl ToString) -> Reference {
    snapshot.reference_for(EntityId::Record(RecordKey {
        family,
        id: id.to_string(),
    }))
}
fn payload(result: ContentResult) -> Value {
    match result {
        ContentResult::Available(content) => match content.value {
            ContentValue::Record(record) => record.payload,
            other => panic!("unexpected content {other:?}"),
        },
        other => panic!("unexpected content {other:?}"),
    }
}

async fn public_contract(store: &Store) {
    let admitted = graph(store, "inspection.test").await;
    let first = run(store, &admitted, "active-self").await;
    let second = run(store, &admitted, "active-other").await;
    let policy = Policy::all();
    let inspector = Inspector::new(store.clone(), policy.clone());
    let host = context("host", None);
    let caller = context("self", Some(first.id.clone()));
    let old = inspector
        .open_snapshot(&caller, RunSelector::Caller, None)
        .await
        .unwrap();
    assert_eq!(old.run_id(), &first.id);
    assert_eq!(
        inspector
            .open_snapshot(&context("self", None), RunSelector::Caller, None)
            .await
            .unwrap_err(),
        InspectionError::InvalidRequest
    );
    assert_eq!(
        inspector
            .open_snapshot(&caller, RunSelector::Id(second.id.clone()), None)
            .await
            .unwrap_err(),
        InspectionError::Denied
    );
    let visible = inspector
        .list_runs(
            &caller,
            InspectionRunFilter::default(),
            PageRequest::new(256),
        )
        .await
        .unwrap();
    assert_eq!(visible.items.len(), 1);
    assert_eq!(visible.items[0].reference.run_id(), &first.id);
    assert_eq!(
        inspector
            .list_runs(&host, InspectionRunFilter::default(), PageRequest::new(256))
            .await
            .unwrap()
            .items
            .len(),
        2
    );
    let selected = reference(&old, RecordFamily::Observation, "mcp-recorded");
    let protected = inspector
        .inspect_entity(&host, &old, &selected)
        .await
        .unwrap();
    assert_eq!(protected.protection.labels, labels());
    assert!(!format!("{protected:?}").contains("response-secret"));
    let original = payload(
        inspector
            .read_content(&host, &old, &selected, ContentKind::Payload, 65536)
            .await
            .unwrap(),
    );
    let history = inspector
        .read_history(&host, &old, Some(&selected), PageRequest::new(256))
        .await
        .unwrap();
    assert_eq!(history.items.len(), 1);
    assert!(!format!("{history:?}").contains("response-secret"));
    let raw_event = inspector
        .read_content(
            &host,
            &old,
            &history.items[0].reference,
            ContentKind::Payload,
            65536,
        )
        .await
        .unwrap();
    assert!(format!("{raw_event:?}").contains("response-secret"));
    let feed_a = inspector
        .read_changes(&host, None, Some(old.position()), 256)
        .await
        .unwrap();
    let feed_b = inspector
        .read_changes(&host, None, Some(old.position()), 256)
        .await
        .unwrap();
    assert_eq!(feed_a.next, feed_b.next);
    assert_eq!(feed_a.items.len(), feed_b.items.len());
    let mut finish = transition(
        "finish",
        vec![write(
            RecordFamily::Observation,
            "mcp-recorded",
            Some(1),
            text("new-secret"),
        )],
    );
    finish.next_status = Some(RunStatus::Succeeded);
    store.commit(&first.lease, finish).await.unwrap();
    let latest = inspector.refresh_snapshot(&caller, &old).await.unwrap();
    assert_ne!(old.position(), latest.position());
    assert_eq!(
        payload(
            inspector
                .read_content(&host, &old, &selected, ContentKind::Payload, 65536)
                .await
                .unwrap()
        ),
        original
    );
    let refreshed = reference(&latest, RecordFamily::Observation, "mcp-recorded");
    assert_eq!(
        payload(
            inspector
                .read_content(&host, &latest, &refreshed, ContentKind::Payload, 65536)
                .await
                .unwrap()
        ),
        text("new-secret")
    );
    assert_eq!(
        inspector
            .inspect_entity(&host, &latest, &selected)
            .await
            .unwrap_err(),
        InspectionError::InvalidReference
    );
    assert_eq!(
        inspector
            .read_history(&host, &old, Some(&selected), PageRequest::new(256))
            .await
            .unwrap()
            .items
            .len(),
        1
    );
    assert_eq!(
        inspector
            .read_history(&host, &latest, Some(&refreshed), PageRequest::new(256))
            .await
            .unwrap()
            .items
            .len(),
        2
    );
    let terminal = inspector
        .list_runs(
            &caller,
            InspectionRunFilter {
                status: Some(RunStatus::Succeeded),
                ..Default::default()
            },
            PageRequest::new(256),
        )
        .await
        .unwrap();
    assert_eq!(terminal.items.len(), 1);
    // A different caller may inspect the same active or terminal run with grants.
    assert!(
        inspector
            .open_snapshot(&host, RunSelector::Id(first.id.clone()), None)
            .await
            .is_ok()
    );
    assert!(
        inspector
            .open_snapshot(&host, RunSelector::Id(second.id.clone()), None)
            .await
            .is_ok()
    );
    let next_a = inspector
        .read_changes(&host, Some(&feed_a.next), None, 256)
        .await
        .unwrap();
    let next_b = inspector
        .read_changes(&host, Some(&feed_b.next), None, 256)
        .await
        .unwrap();
    assert_eq!(next_a.next, next_b.next);
    assert!(!next_a.items.is_empty());
    for item in &next_a.items {
        let (_, entity) = inspector
            .resolve_reference(&host, &item.reference)
            .await
            .unwrap();
        assert_eq!(entity.reference.position_number(), item.position.number());
    }
    // Current discovery/structure/content are independent on every call/page.
    policy.content.store(false, Ordering::SeqCst);
    assert!(
        inspector
            .inspect_entity(&host, &old, &selected)
            .await
            .is_ok()
    );
    assert_eq!(
        inspector
            .read_content(&host, &old, &selected, ContentKind::Payload, 65536)
            .await
            .unwrap_err(),
        InspectionError::Denied
    );
    assert_eq!(
        inspector
            .read_content(
                &host,
                &old,
                &history.items[0].reference,
                ContentKind::Payload,
                65536
            )
            .await
            .unwrap_err(),
        InspectionError::Denied
    );
    policy.structure.store(false, Ordering::SeqCst);
    policy.content.store(true, Ordering::SeqCst);
    assert_eq!(
        inspector
            .inspect_entity(&host, &old, &selected)
            .await
            .unwrap_err(),
        InspectionError::Denied
    );
    assert!(
        inspector
            .read_content(&host, &old, &selected, ContentKind::Payload, 65536)
            .await
            .is_ok()
    );
    assert!(
        inspector
            .list_entities(
                &host,
                &old,
                EntityKind::Records(RecordFamily::Observation),
                PageRequest::new(1)
            )
            .await
            .unwrap()
            .items
            .is_empty()
    );
    policy.structure.store(true, Ordering::SeqCst);
    *policy.hidden.lock().unwrap() = Some(selected.entity.clone());
    assert_eq!(
        inspector
            .resolve_reference(&host, &selected)
            .await
            .unwrap_err(),
        InspectionError::Denied
    );
    let hidden = inspector
        .list_entities(
            &host,
            &old,
            EntityKind::Records(RecordFamily::Observation),
            PageRequest::new(1),
        )
        .await
        .unwrap();
    assert!(hidden.items.is_empty());
    assert!(hidden.next.is_some());
    assert_eq!(
        inspector
            .read_content(&host, &old, &selected, ContentKind::Payload, 65536)
            .await
            .unwrap_err(),
        InspectionError::Denied
    );
    *policy.hidden.lock().unwrap() = None;
    policy.discover.store(false, Ordering::SeqCst);
    assert!(
        inspector
            .list_runs(&host, InspectionRunFilter::default(), PageRequest::new(1))
            .await
            .unwrap()
            .items
            .is_empty()
    );
    assert_eq!(
        inspector.refresh_snapshot(&host, &old).await.unwrap_err(),
        InspectionError::Denied
    );
    assert!(
        inspector
            .read_changes(&host, None, None, 256)
            .await
            .unwrap()
            .items
            .is_empty()
    );
    policy.discover.store(true, Ordering::SeqCst);
    assert!(matches!(
        inspector
            .read_content(&host, &old, &selected, ContentKind::Payload, 1)
            .await
            .unwrap(),
        ContentResult::Unavailable(UnavailableReason::TooLarge)
    ));
    // Inspection dispatches nothing: no header sequence changed after all reads.
    assert_eq!(
        store.run_header(&first.id).await.unwrap().sequence,
        latest.stored.header().sequence
    );
    assert_eq!(
        store.run_header(&second.id).await.unwrap().sequence,
        old.stored.header().sequence
    );
}

